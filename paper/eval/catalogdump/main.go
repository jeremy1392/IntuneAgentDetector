// Command catalogdump writes the appendix tables of the paper from the
// embedded catalog, through the same loader as the detector, so that the
// appendix cannot drift from the evaluated catalog.
//
// Usage (from the repository root): go run ./paper/eval/catalogdump
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"detectoragent/internal/catalog"
	"detectoragent/rules"
)

func main() {
	cat, err := catalog.Load(rules.Default)
	if err != nil {
		fmt.Fprintln(os.Stderr, "catalog:", err)
		os.Exit(1)
	}
	dir := filepath.Join("paper", "eval", "results", "tex")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	write(filepath.Join(dir, "app-tools.tex"), toolsTable(cat))
	write(filepath.Join(dir, "app-endpoints.tex"), endpointsTable(cat))
	write(filepath.Join(dir, "app-generic.tex"), genericList(cat))
	fmt.Printf("catalog %s: %d tools, %d endpoints\n", cat.Version, len(cat.Tools), len(cat.Endpoints))
}

func write(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func esc(s string) string {
	r := strings.NewReplacer(`\`, `\textbackslash{}`, `{`, `\{`, `}`, `\}`, `_`, `\_`, `%`, `\%`,
		`&`, `\&`, `#`, `\#`, `$`, `\$`, `^`, `\textasciicircum{}`, `~`, `\textasciitilde{}`)
	return r.Replace(s)
}

// escBreak escapes like esc and allows line breaks inside long identifiers
// and patterns, after separators.
func escBreak(s string) string {
	r := strings.NewReplacer(`\`, `\textbackslash{}\allowbreak{}`, `{`, `\{`, `}`, `\}`, `_`, `\_\allowbreak{}`,
		`%`, `\%`, `&`, `\&`, `#`, `\#`, `$`, `\$`, `^`, `\textasciicircum{}`, `~`, `\textasciitilde{}`,
		`|`, `|\allowbreak{}`, `/`, `/\allowbreak{}`, `.`, `.\allowbreak{}`, `-`, `-\allowbreak{}`, `(`, `\allowbreak{}(`, `]`, `]\allowbreak{}`, `*`, `*\allowbreak{}`)
	return r.Replace(s)
}

// signals lists the kinds of identifiers that recognize a tool.
func signals(t *catalog.Tool) string {
	var out []string
	add := func(ok bool, label string) {
		if ok {
			out = append(out, label)
		}
	}
	p := t.Process
	add(len(p.Images) > 0, "image")
	add(len(p.Products) > 0, "product")
	add(len(p.Signers) > 0, "signer")
	add(len(p.Paths) > 0, "path")
	add(len(p.Cmdline) > 0, "cmdline")
	add(len(t.Packages) > 0, "MSIX")
	add(len(t.Services) > 0, "service")
	add(len(t.Uninstall) > 0, "uninstall")
	add(len(t.VSCodeExtensions) > 0 || len(t.JetBrainsPlugins) > 0 || len(t.BrowserExtensions) > 0, "extension")
	add(len(t.NPM) > 0, "npm")
	add(len(t.PIP) > 0, "pip")
	add(len(t.Installed) > 0, "files")
	add(len(t.History) > 0, "history")
	add(len(t.Residue) > 0, "residue")
	add(len(t.MCPConfigs) > 0, "MCP config")
	add(len(t.Models) > 0, "models")
	add(len(t.Ports) > 0, "port")
	add(len(t.Env) > 0, "env")
	return strings.Join(out, ", ")
}

func toolsTable(cat *catalog.Catalog) string {
	tools := append([]*catalog.Tool(nil), cat.Tools...)
	sort.SliceStable(tools, func(i, j int) bool {
		if tools[i].Category != tools[j].Category {
			return tools[i].Category < tools[j].Category
		}
		return tools[i].ID < tools[j].ID
	})
	var b strings.Builder
	b.WriteString("% Generated by paper/eval/catalogdump: do not edit.\n")
	b.WriteString("\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{2.8cm} >{\\raggedright\\arraybackslash}p{3.8cm} >{\\raggedright\\arraybackslash}p{2.0cm} >{\\raggedright\\arraybackslash}p{4.0cm}@{}}\n")
	b.WriteString("\\caption{Tool signatures of the evaluated catalog (version " + esc(cat.Version) + ").}\\label{tab:app-tools}\\\\\n")
	b.WriteString("\\toprule Id & Tool & Category & Identifiers \\\\ \\midrule\n\\endfirsthead\n")
	b.WriteString("\\toprule Id & Tool & Category & Identifiers \\\\ \\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n")
	for _, t := range tools {
		fmt.Fprintf(&b, "\\code{%s} & %s & %s & %s \\\\\n", escBreak(t.ID), esc(t.Name), escBreak(t.Category), esc(signals(t)))
	}
	b.WriteString("\\end{longtable}\n")
	return b.String()
}

func endpointsTable(cat *catalog.Catalog) string {
	eps := append([]*catalog.Endpoint(nil), cat.Endpoints...)
	sort.SliceStable(eps, func(i, j int) bool {
		if eps[i].Category != eps[j].Category {
			return eps[i].Category < eps[j].Category
		}
		return eps[i].Key() < eps[j].Key()
	})
	var b strings.Builder
	b.WriteString("% Generated by paper/eval/catalogdump: do not edit.\n")
	b.WriteString("{\\footnotesize\n\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{2.4cm} >{\\raggedright\\arraybackslash}p{5.6cm} >{\\raggedright\\arraybackslash}p{5.0cm}@{}}\n")
	b.WriteString("\\caption{Endpoint entries of the evaluated catalog (version " + esc(cat.Version) + "). A suffix entry matches every subdomain; ``shared'' marks hosts that also serve non-AI traffic; ``unverified'' marks entries not yet confirmed on an official source when the catalog was frozen.}\\label{tab:app-endpoints}\\\\\n")
	b.WriteString("\\toprule Category & Entry & Provider \\\\ \\midrule\n\\endfirsthead\n")
	b.WriteString("\\toprule Category & Entry & Provider \\\\ \\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n")
	for _, e := range eps {
		entry := ""
		switch {
		case e.Host != "":
			entry = e.Host
		case e.Suffix != "":
			entry = "*" + e.Suffix
		case e.CIDR != "":
			entry = e.CIDR
		default:
			entry = "pattern " + e.Pattern
		}
		var flags []string
		if e.Shared {
			flags = append(flags, "shared")
		}
		if e.Unverified {
			flags = append(flags, "unverified")
		}
		provider := esc(e.Provider)
		if len(flags) > 0 {
			provider += " \\emph{(" + strings.Join(flags, ", ") + ")}"
		}
		fmt.Fprintf(&b, "%s & \\code{%s} & %s \\\\\n", esc(e.Category), escBreak(entry), provider)
	}
	b.WriteString("\\end{longtable}\n}\n")
	return b.String()
}

func genericList(cat *catalog.Catalog) string {
	g := cat.Generic
	var b strings.Builder
	b.WriteString("% Generated by paper/eval/catalogdump: do not edit.\n{\\sloppy\n\\begin{description}[leftmargin=1.2em,style=nextline]\n")
	item := func(label string, values []string) {
		quoted := make([]string, len(values))
		for i, v := range values {
			quoted[i] = "\\code{" + escBreak(v) + "}"
		}
		fmt.Fprintf(&b, "  \\item[%s] %s\n", label, strings.Join(quoted, ", "))
	}
	item("Shells and interpreters counted as agent actions", g.Shells)
	item("Interpreters whose modules and environment are inspected", g.Interpreters)
	item("Browsers (excluded from network attribution)", g.Browsers)
	item("Browser automation flags", g.BrowserAutomationFlags)
	item("MCP server command-line patterns", g.MCPCmdline)
	item("Inference module patterns", g.InferenceModules)
	item("Tokenizer module patterns", g.TokenizerModules)
	item("Base-URL variable patterns", g.BaseURLVars)
	item("API-key variable patterns", g.APIKeyVars)
	b.WriteString("\\end{description}\n}\n")
	return b.String()
}
